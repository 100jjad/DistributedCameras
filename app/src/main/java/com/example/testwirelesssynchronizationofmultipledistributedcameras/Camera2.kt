    // تابع جدید برای تنظیم زوم
    fun setZoom(zoomLevel: Float) {
        // zoomLevel باید بین 1 (بدون زوم) و maxDigitalZoom باشد
        val newZoom = zoomLevel.coerceIn(1f, maxDigitalZoom)
        currentZoom = newZoom  // ذخیره مقدار زوم فعلی
        sensorArraySize?.let { sensorRect ->
            val centerX = sensorRect.centerX()
            val centerY = sensorRect.centerY()
            // محاسبه عرض و ارتفاع جدید crop region بر اساس زوم
            val newWidth = (sensorRect.width() / newZoom).toInt()
            val newHeight = (sensorRect.height() / newZoom).toInt()
            val left = centerX - newWidth / 2
            val top = centerY - newHeight / 2
            val right = left + newWidth
            val bottom = top + newHeight
            val zoomRect = Rect(left, top, right, bottom)
            captureRequestBuilder?.set(CaptureRequest.SCALER_CROP_REGION, zoomRect)
            captureRequest = captureRequestBuilder?.build()
            try {
                cameraCaptureSession?.setRepeatingRequest(
                    captureRequest!!,
                    cameraCaptureCallBack,
                    backgroundHandler
                )
            } catch (e: CameraAccessException) {
                e.printStackTrace()
            }
        }
    }


    /**
     * تابع برای پیکربندی MediaRecorder
     * پارامتر outputFile مسیر فایل خروجی ضبط شده است.
     */

    private fun setUpMediaRecorder(context: Context, outputFile: String, framerate: Int) {
        mediaRecorder = MediaRecorder()
        mediaRecorder?.apply {
            // تنظیم منابع صوتی و تصویری
            setAudioSource(MediaRecorder.AudioSource.MIC)
            setVideoSource(MediaRecorder.VideoSource.SURFACE)

            Log.d("Camera2", "Video will be saved at: $outputFile")

            // تنظیم فرمت خروجی
            setOutputFormat(MediaRecorder.OutputFormat.MPEG_4)


            // در اندروید 13 و بالاتر، از MediaStore استفاده کنید
            if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.TIRAMISU) {
                val values = ContentValues().apply {
                    // نام فایل خروجی به صورت منحصر به فرد
                    put(
                        MediaStore.Video.Media.DISPLAY_NAME,
                        "video_${System.currentTimeMillis()}.mp4"
                    )
                    put(MediaStore.Video.Media.MIME_TYPE, "video/mp4")
                    // ذخیره در پوشه عمومی Movies (یا Videos)
                    put(
                        MediaStore.Video.Media.RELATIVE_PATH,
                        Environment.DIRECTORY_MOVIES + "/DistributedCameras"
                    )
                }
                val resolver = context.contentResolver
                val videoUri = resolver.insert(MediaStore.Video.Media.EXTERNAL_CONTENT_URI, values)
                if (videoUri != null) {
                    val fd = resolver.openFileDescriptor(videoUri, "w")?.fileDescriptor
                    if (fd != null) {
                        setOutputFile(fd)
                    } else {
                        Log.e("Camera2", "Failed to obtain FileDescriptor for videoUri")
                    }
                } else {
                    Log.e("Camera2", "Failed to insert video into MediaStore")
                }
            } else {
                // برای نسخه‌های پایین‌تر از اندروید 13، مسیر فایل خروجی مستقیم مورد استفاده قرار می‌گیرد
                try {
                    // **اینجا مسیر فایل خروجی را تنظیم کنید**
                    setOutputFile(outputFile)
                    Log.d("Camera2", "MediaRecorder setup successful")
                } catch (e: Exception) {
                    Log.e("Camera2", "Error in MediaRecorder setup: ${e.message}")
                }
            }

            // تنظیمات کدگذاری ویدئو – می‌توانید این مقادیر را تغییر دهید
            setVideoEncodingBitRate(10000000)
            setVideoFrameRate(framerate)
            // اندازه ویدئو را بر اساس previewSize انتخاب می‌کنیم
            previewSize?.let {
                setVideoSize(it.width, it.height)
            } ?: run {
                // در صورت نبود اندازه مناسب، از یک مقدار پیش‌فرض استفاده کنید
                setVideoSize(1920, 1080)
            }
            setVideoEncoder(MediaRecorder.VideoEncoder.H264)
            setAudioEncoder(MediaRecorder.AudioEncoder.AAC)

            // تنظیم جهت چرخش ویدئو بر اساس جهت سنسور
            val rotation = activity.windowManager.defaultDisplay.rotation
            val orientation = getOrientation(rotation)
            setOrientationHint(orientation)

            prepare()
        }
    }


    /**
     * پیش‌پیکربندی session ضبط ویدئو با استفاده از یک capture session مشترک برای پیش‌نمایش و ضبط.
     * این متد باید قبل از شروع ضبط (و بعد از آنکه کاربر آماده ضبط شود) فراخوانی شود.
     */
    fun prepareVideoRecordingSession(
        context: Context,
        outputFile: String,
        currentExposureValue: Long,
        currentIsoValue: Int,
        currentFocusValue: Float,
        framerate: Int,
        autostart: Boolean = false
    ) {
        // محاسبه یک‌باره در شروع ضبط
        val currentTimeMillis = System.currentTimeMillis()
        val elapsedRealtimeNanos = SystemClock.elapsedRealtimeNanos()
        bootTimeMillis = currentTimeMillis - (elapsedRealtimeNanos / 1_000_000)

        if (cameraDevice == null || !textureView.isAvailable || previewSize == null) return

        cameraCaptureSession?.close()
        cameraCaptureSession = null
        videoTimestamps.clear()

        // پیکربندی MediaRecorder
        setUpMediaRecorder(context, outputFile, framerate)
        timestampFilePath = outputFile // ذخیره موقت مسیر فایل ویدئو

        // تنظیم اندازه بافر سطح TextureView
        val texture = textureView.surfaceTexture
        texture?.setDefaultBufferSize(previewSize!!.width, previewSize!!.height)
        val previewSurface = Surface(texture)
        val recorderSurface = mediaRecorder!!.surface

        // ایجاد CaptureRequest برای حالت ضبط (TEMPLATE_RECORD)
        captureRequestBuilder =
            cameraDevice!!.createCaptureRequest(CameraDevice.TEMPLATE_RECORD).apply {
                set(CaptureRequest.CONTROL_AE_MODE, CaptureRequest.CONTROL_AE_MODE_OFF)
                set(CaptureRequest.SENSOR_EXPOSURE_TIME, currentExposureValue)
                set(CaptureRequest.SENSOR_SENSITIVITY, currentIsoValue)
                set(CaptureRequest.CONTROL_AF_MODE, CaptureRequest.CONTROL_AF_MODE_OFF)
                set(CaptureRequest.LENS_FOCUS_DISTANCE, currentFocusValue)
                addTarget(previewSurface)
                addTarget(recorderSurface)

                // اعمال زوم فعلی به CaptureRequest
                if (currentZoom > 1f) {
                    sensorArraySize?.let { sensorRect ->
                        val centerX = sensorRect.centerX()
                        val centerY = sensorRect.centerY()
                        val newWidth = (sensorRect.width() / currentZoom).toInt()
                        val newHeight = (sensorRect.height() / currentZoom).toInt()
                        val left = centerX - newWidth / 2
                        val top = centerY - newHeight / 2
                        val right = left + newWidth
                        val bottom = top + newHeight
                        val zoomRect = Rect(left, top, right, bottom)
                        set(CaptureRequest.SCALER_CROP_REGION, zoomRect)
                    }
                }
            }


        // ایجاد یک capture session مشترک شامل هر دو سطح
        cameraDevice!!.createCaptureSession(
            listOf(previewSurface, recorderSurface),
            object : CameraCaptureSession.StateCallback() {
                override fun onConfigured(session: CameraCaptureSession) {
                    cameraCaptureSession = session
                    captureRequest = captureRequestBuilder!!.build()
                    // شروع به ارسال درخواست‌های تکراری
                    cameraCaptureSession!!.setRepeatingRequest(
                        captureRequest!!,
                        timestampCollectingCallback,
                        backgroundHandler
                    )
                    Log.d("Camera2", "Shared capture session for preview and recording configured")
                }

                override fun onConfigureFailed(session: CameraCaptureSession) {
                    Log.e("Camera2", "Configuration failed when preparing video session")
                }
            },
            backgroundHandler
        )

        if (autostart)
            startRecordingVideo()
    }

    /**
     * شروع ضبط ویدئو با استفاده از session از پیش پیکربندی‌شده.
     * در اینجا نیازی به ایجاد session جدید نیست؛ فقط ضبط توسط MediaRecorder آغاز می‌شود.
     */
    fun startRecordingVideo() {
        try {
            // شروع ضبط به صورت فوری
            mediaRecorder?.start()
            isRecordingVideo = true
            Log.d("Camera2", "Video recording started with zero reconfiguration delay")
        } catch (e: Exception) {
            e.printStackTrace()
            Log.e("Camera2", "Error while starting video recording: ${e.message}")
        }
    }


    /**
     * توقف ضبط ویدئو.
     * پس از توقف، یک session جدید preview ایجاد می‌شود.
     */
    fun stopRecordingVideo() {
        if (!isRecordingVideo) {
            Log.e("Camera2", "MediaRecorder stop called while not recording!")
            return
        } else {
            try {
                isRecordingVideo = false
                // توقف ضبط
                mediaRecorder?.apply {
                    try {
                        stop()
                        reset()
                        release()
                    } catch (e: Exception) {
                        // در صورت خطا (مثلاً اگر ضبط به درستی آغاز نشده باشد)
                        e.printStackTrace()
                        Log.e(
                            "Camera2",
                            "MediaRecorder stop called while not recording! : ${e.message}"
                        )
                    }
                }
                mediaRecorder = null
                // ذخیره timestampها بعد از توقف
                timestampFilePath?.let { saveTimestampsToFile(activity, it) } // activity به عنوان context
                cameraCaptureSession?.close()
                cameraCaptureSession = null
            } catch (e: Exception) {
                Log.e("Camera2", "خطا در توقف ضبط: ${e.message}")
                e.printStackTrace()
            }
        }
        // بازگرداندن preview
        createPreviewSession()

    }




    fun collectTimestampsWithoutStopping(numFrames: Int = 50, callback: (List<Long>) -> Unit) {
        val timestamps = mutableListOf<Long>()
        val captureCallback = object : CameraCaptureSession.CaptureCallback() {
            override fun onCaptureCompleted(
                session: CameraCaptureSession,
                request: CaptureRequest,
                result: TotalCaptureResult
            ) {
                val timestamp = result.get(CaptureResult.SENSOR_TIMESTAMP) ?: return
                timestamps.add(timestamp)
                if (timestamps.size == numFrames) { // دقیقاً وقتی به numFrames رسید
                    callback(timestamps) // فراخوانی callback با لیست timestampها
                    // برگرداندن درخواست تکراری به حالت اصلی
                    try {
                        session.setRepeatingRequest(
                            captureRequest!!, // درخواست اصلی پیش‌نمایش
                            cameraCaptureCallBack, // callback اصلی پیش‌نمایش
                            backgroundHandler
                        )
                    } catch (e: CameraAccessException) {
                        Log.e("Camera2", "Error resetting repeating request: ${e.message}")
                    }
                }
            }
        }

        try {
            cameraCaptureSession?.setRepeatingRequest(
                captureRequestBuilder!!.build(),
                captureCallback,
                backgroundHandler
            )
        } catch (e: CameraAccessException) {
            Log.e("Camera2", "Error collecting timestamps: ${e.message}")
        }
    }

    // Callback جدید برای جمع‌آوری timestampها در حین ضبط ویدئو
// Wrapper برای cameraCaptureCallBack که timestampها رو هم جمع‌آوری می‌کنه
    private val timestampCollectingCallback = object : CameraCaptureSession.CaptureCallback() {
        override fun onCaptureCompleted(
            session: CameraCaptureSession,
            request: CaptureRequest,
            result: TotalCaptureResult
        ) {
            // اجرای منطق اصلی cameraCaptureCallBack
            cameraCaptureCallBack.onCaptureCompleted(session, request, result)

            // جمع‌آوری timestamp بدون تغییر در رفتار اصلی
            //val timestamp = result.get(CaptureResult.SENSOR_TIMESTAMP) ?: return
            //videoTimestamps.add(timestamp)

            // جمع‌آوری timestamp و تبدیل به زمان Unix
            val sensorTimestamp = result.get(CaptureResult.SENSOR_TIMESTAMP) ?: return
            val unixTimestamp = convertToUnixTime(sensorTimestamp)
            videoTimestamps.add(unixTimestamp)
        }

        override fun onCaptureProgressed(
            session: CameraCaptureSession,
            request: CaptureRequest,
            partialResult: CaptureResult
        ) {
            // اجرای منطق اصلی cameraCaptureCallBack
            cameraCaptureCallBack.onCaptureProgressed(session, request, partialResult)
        }
    }

    // متد ذخیره timestampها در فایل
    private fun saveTimestampsToFile(context: Context, videoFileName: String) {
        // چک می‌کنیم که آیا timestamp داریم یا نه
        if (videoTimestamps.isEmpty()) {
            Log.e("Camera2", "هیچ timestampی جمع‌آوری نشده!")
            return
        }

// استخراج فقط نام فایل ویدئو بدون مسیر
        val videoFileName = File(videoFileName).name

        // ساخت نام فایل timestamp بر اساس نام ویدئو
        val timestampFileName = videoFileName.replace(".mp4", "_timestamps.txt")

        // ذخیره با MediaStore برای همه نسخه‌ها
        val values = ContentValues().apply {
            put(MediaStore.Files.FileColumns.DISPLAY_NAME, timestampFileName)
            put(MediaStore.Files.FileColumns.MIME_TYPE, "text/plain")
            put(MediaStore.Files.FileColumns.RELATIVE_PATH, Environment.DIRECTORY_DOCUMENTS + "/DistributedCameras")
        }

        val resolver = context.contentResolver
        val uri = resolver.insert(MediaStore.Files.getContentUri("external"), values)
        uri?.let {
            resolver.openOutputStream(it)?.use { outputStream ->
                outputStream.write(videoTimestamps.joinToString("\n").toByteArray())
            }
            Log.d("Camera2", "فایل timestamp در $uri ذخیره شد")
            // نمایش پیام به کاربر
            (context as? Activity)?.runOnUiThread {
                Toast.makeText(context, "Timestamps have been saved in DCIM/DistributedCameras", Toast.LENGTH_SHORT).show();
            }
        } ?: run {
            Log.e("Camera2", "خطا در ایجاد فایل timestamp")
        }
    }

    private fun convertToUnixTime(sensorTimestamp: Long): Long {
        if (role == "slave")
        {
            val unixTimeMillis = bootTimeMillis + (sensorTimestamp / 1_000_000) // زمان Unix محلی
            val offset = TimeSyncManager.getOffset() // افست محاسبه‌شده
            return unixTimeMillis + offset // زمان هماهنگ‌شده با مستر
        }
        else{
            // استفاده از مقدار ذخیره‌شده
            val unixTimeMillis = bootTimeMillis + (sensorTimestamp / 1_000_000)
            return unixTimeMillis
        }
    }



